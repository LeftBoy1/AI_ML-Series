#Vector, Matrice & Tensor
import numpy as np
vector = np.array([2,3])            #1 Dimension
print("\n",vector)

matrice = np.array([[2,3],[4,3]])       #2 Dimension
print("\n",matrice)

tensor = np.array([[[1,2],[2,4]],[[2,1],[4,3]]])
print("\n",tensor)


'''Scalar → 1 number
Vector → 1D array
Matrix → 2D array
Tensor  → 3D or higher-dimensional array
'''
